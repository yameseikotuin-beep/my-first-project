import type { Food, FoodCategory, FoodRole, FoodState, Allergen } from '../types'

/**
 * 食品成分データ（可食部100gあたり）。
 *
 * 出典: 文部科学省「日本食品標準成分表2020年版（八訂）」。
 * 値は成分表の「エネルギー(kcal)」「たんぱく質」「脂質」「炭水化物」
 * 「食物繊維総量」「食塩相当量」の各列を食品番号ごとに手入力したもの。
 * この開発環境からは公式ファイル（mext.go.jp）を取得できなかったため、
 * verification は 'transcribed'（公式ファイル未照合）としている。
 * scripts/import-mext.mjs に公式ファイル（CSV）を渡すと、食品番号で照合して
 * 値を上書きし、verification を 'verified' に更新できる。
 */
export const FOOD_SOURCE = '日本食品標準成分表2020年版（八訂）'
export const FOOD_SOURCE_VERSION = '2020（八訂）'
export const FOOD_DATA_UPDATED = '2026-10-02'

type Nut = [kcal: number, protein: number, fat: number, carbs: number, fiber: number, salt: number]

interface Opts {
  aliases?: string[]
  allergens?: Allergen[]
  unit?: { name: string; grams: number }
  verification?: Food['verification']
}

function f(
  id: string,
  name: string,
  displayName: string,
  category: FoodCategory,
  role: FoodRole,
  state: FoodState,
  n: Nut,
  opts: Opts = {},
): Food {
  return {
    id,
    name,
    displayName,
    aliases: opts.aliases ?? [],
    category,
    role,
    state,
    referenceWeight: 100,
    calories: n[0],
    protein: n[1],
    fat: n[2],
    carbohydrates: n[3],
    fiber: n[4],
    salt: n[5],
    allergens: opts.allergens ?? [],
    unit: opts.unit,
    source: FOOD_SOURCE,
    sourceVersion: FOOD_SOURCE_VERSION,
    updatedAt: FOOD_DATA_UPDATED,
    verification: opts.verification ?? 'transcribed',
    estimated: false,
  }
}

